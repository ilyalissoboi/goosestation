# Writes the Android app's launcher icon from the design system's goose mark (docs/design-system/logos/goose-mark.svg
# and goose-mark-mono.svg): an adaptive icon of vector layers, which every Android the app supports (API 29 and up)
# draws at any size, so there are no PNGs per density. Standard library only. Run from anywhere:
#   python scripts/branding/generate-android-icon.py
#
# The layers are on the adaptive icon's 108 dp canvas. Launchers show the middle 72 dp through a mask of their own
# shape (circle, squircle, rounded square) and may move the layers by up to 18 dp, so everything that must show, the
# head and the beak, stays in the 66 dp circle at the centre. The neck runs off the bottom of the canvas, so the goose
# rises out of the bottom edge whatever the mask.
#
#   background   the design system's `surface`, the app icon's dark tile
#   foreground   the mark in full colour
#   monochrome   the mark's silhouette with the eye cut out, which Android 13 and up tint for themed icons

import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOGOS = ROOT / "docs" / "design-system" / "logos"
RES = ROOT / "android" / "app" / "src" / "main" / "res"

# The design system's `surface` (dark): the app icon's tile.
BACKGROUND = "#FF161A21"

# The mark's 64-unit grid onto the 108 dp canvas: scaled by SCALE, then moved by (DX, DY). Its head and beak (x 14 to
# 58, y 9 to 30) come out centred across, a little above the middle, so the neck shows under them.
SCALE = 1.25
DX = 9.0
DY = 22.875

# The adaptive icon's safe zone: a circle of 66 dp at the canvas's centre.
SAFE_CENTRE = 54.0
SAFE_RADIUS = 33.0

HEADER = """<?xml version="1.0" encoding="utf-8"?>
<!-- SPDX-FileCopyrightText: 2026 GooseStation contributors -->
<!-- SPDX-License-Identifier: GPL-3.0 -->
<!-- Generated by scripts/branding/generate-android-icon.py from docs/design-system/logos: don't edit by hand. -->
"""


def shapes(svg: Path) -> list[tuple[str, list[tuple[float, float]]]]:
    """The fill and corners of each polygon and rect in [svg], in order. A fill can be on the shape or its group."""
    text = svg.read_text(encoding="utf-8")
    group_fill = re.search(r'<g[^>]*fill="([^"]+)"', text)
    out = []
    for tag, attributes in re.findall(r"<(polygon|rect)\s([^>]*?)/>", text):
        attrs = dict(re.findall(r'([\w-]+)="([^"]*)"', attributes))
        fill = attrs.get("fill") or (group_fill.group(1) if group_fill else None)
        if fill is None:
            sys.exit(f"{svg.name}: a <{tag}> with no fill")
        if tag == "polygon":
            points = [tuple(float(v) for v in p.split(",")) for p in attrs["points"].split()]
        else:
            x, y, w, h = (float(attrs[k]) for k in ("x", "y", "width", "height"))
            points = [(x, y), (x + w, y), (x + w, y + h), (x, y + h)]
        out.append((fill, points))
    if not out:
        sys.exit(f"{svg.name}: no shapes found")
    return out


def number(value: float) -> str:
    return f"{value:.3f}".rstrip("0").rstrip(".")


def path_data(points: list[tuple[float, float]]) -> str:
    return "M" + " L".join(f"{number(x)},{number(y)}" for x, y in points) + " Z"


def colour(fill: str) -> str:
    """An SVG #rrggbb as Android's #AARRGGBB."""
    if not re.fullmatch(r"#[0-9a-fA-F]{6}", fill):
        sys.exit(f"Can't read the fill {fill}: the marks use #rrggbb")
    return "#FF" + fill[1:].upper()


def check_safe_zone(head_and_beak: list[tuple[float, float]]) -> None:
    for x, y in head_and_beak:
        cx, cy = x * SCALE + DX, y * SCALE + DY
        if math.hypot(cx - SAFE_CENTRE, cy - SAFE_CENTRE) > SAFE_RADIUS:
            sys.exit(f"({x}, {y}) lands at ({cx}, {cy}), outside the 66 dp safe zone: adjust SCALE, DX or DY")


def vector(body: str) -> str:
    return (
        HEADER
        + '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        + '    android:width="108dp"\n    android:height="108dp"\n'
        + '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        + f'    <group\n        android:scaleX="{number(SCALE)}"\n        android:scaleY="{number(SCALE)}"\n'
        + f'        android:translateX="{number(DX)}"\n        android:translateY="{number(DY)}">\n'
        + body
        + "    </group>\n</vector>\n"
    )


def write(relative: str, text: str) -> None:
    path = RES / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")
    print(path.relative_to(ROOT))


def main() -> None:
    mark = shapes(LOGOS / "goose-mark.svg")
    mono = shapes(LOGOS / "goose-mark-mono.svg")

    # Everything above the neck's foot must show: every corner the mark has above y = 30.
    check_safe_zone([p for _, points in mark for p in points if p[1] <= 30])

    foreground = "".join(
        f'        <path\n            android:fillColor="{colour(fill)}"\n'
        f'            android:pathData="{path_data(points)}" />\n'
        for fill, points in mark
    )
    # The silhouette and the eye as one path, the eye a hole by the even-odd rule: a themed icon is tinted by the
    # layer's alpha, so a white eye would be tinted like the rest.
    outline, *holes = [points for _, points in mono]
    silhouette = " ".join(path_data(points) for points in [outline, *holes])
    monochrome = (
        '        <path\n            android:fillColor="#FF000000"\n            android:fillType="evenOdd"\n'
        f'            android:pathData="{silhouette}" />\n'
    )

    write("drawable/ic_launcher_foreground.xml", vector(foreground))
    write("drawable/ic_launcher_monochrome.xml", vector(monochrome))
    write(
        "values/ic_launcher.xml",
        HEADER + f'<resources>\n    <color name="ic_launcher_background">{BACKGROUND}</color>\n</resources>\n',
    )
    adaptive = (
        HEADER
        + '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        + '    <background android:drawable="@color/ic_launcher_background" />\n'
        + '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        + '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        + "</adaptive-icon>\n"
    )
    write("mipmap-anydpi/ic_launcher.xml", adaptive)
    write("mipmap-anydpi/ic_launcher_round.xml", adaptive)


if __name__ == "__main__":
    main()
