#!/usr/bin/env python3
# SPDX-License-Identifier: GPL-3.0
#
# Writes the Android app's GsIcons.kt from the design system's icons, docs/design-system/icons/*.svg, so the app
# draws exactly what the design system does. Standard library only. Run from anywhere after adding or changing an
# icon:
#   python scripts/branding/generate-gsicons.py
#
# The SVGs are kept to the shapes the icon grid uses: <polygon>, <polyline>, <rect> and <path> with M, L, H and V
# (absolute) commands. Anything else stops the script with the file and the element it can't read.

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ICONS = ROOT / "docs" / "design-system" / "icons"
OUT = ROOT / "android/app/src/main/java/io/github/ilyalissoboi/goosestation/ui/theme/GsIcons.kt"

HEADER = """// SPDX-FileCopyrightText: 2026 GooseStation contributors
// SPDX-License-Identifier: GPL-3.0

// Generated by scripts/branding/generate-gsicons.py from docs/design-system/icons: don't edit by hand.

package io.github.ilyalissoboi.goosestation.ui.theme

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathBuilder
import androidx.compose.ui.graphics.vector.path
import androidx.compose.ui.unit.dp

/**
 * GooseStation's icons, as the design system draws them: a 24 dp grid, 2 dp strokes, square caps, mitred corners,
 * octagons where a circle would be. Drawn in black; [androidx.compose.material3.Icon]'s tint colours them.
 */
object GsIcons {
"""

FOOTER = """}

private fun icon(
    name: String,
    draw: PathBuilder.() -> Unit,
): ImageVector =
    ImageVector
        .Builder(name = name, defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 24f, viewportHeight = 24f)
        .path(
            fill = null,
            stroke = SolidColor(Color.Black),
            strokeLineWidth = 2f,
            strokeLineCap = StrokeCap.Square,
            strokeLineJoin = StrokeJoin.Miter,
            pathBuilder = draw,
        ).build()
"""


def number(value: str) -> str:
    text = f"{float(value):.2f}".rstrip("0").rstrip(".")
    return text + "f"


def point(x: str, y: str, command: str) -> str:
    return f"{command}({number(x)}, {number(y)})"


def path_commands(d: str, where: str) -> list[str]:
    tokens = re.findall(r"[A-Za-z]|-?\d*\.?\d+", d)
    commands, command, x, y, i = [], None, 0.0, 0.0, 0
    while i < len(tokens):
        token = tokens[i]
        if token.isalpha():
            if token not in "MLHV":
                sys.exit(f"{where}: path command {token} isn't one of M, L, H, V")
            command = token
            i += 1
            continue
        if command in ("M", "L"):
            x, y = float(tokens[i]), float(tokens[i + 1])
            i += 2
            commands.append(point(str(x), str(y), "moveTo" if command == "M" else "lineTo"))
            # Pairs after an M are lines, as in SVG.
            if command == "M":
                command = "L"
        elif command == "H":
            x = float(token)
            i += 1
            commands.append(point(str(x), str(y), "lineTo"))
        elif command == "V":
            y = float(token)
            i += 1
            commands.append(point(str(x), str(y), "lineTo"))
        else:
            sys.exit(f"{where}: a number before any command")
    return commands


def commands_for(svg: Path) -> list[str]:
    body = svg.read_text(encoding="utf-8")
    out = []
    for tag, attributes in re.findall(r"<(\w+)\s([^>]*?)/>", body):
        attrs = dict(re.findall(r'([\w-]+)="([^"]*)"', attributes))
        where = f"{svg.name}: <{tag}>"
        if tag in ("polygon", "polyline"):
            points = [p.split(",") for p in attrs["points"].split()]
            out.append(point(*points[0], "moveTo"))
            out += [point(x, y, "lineTo") for x, y in points[1:]]
            if tag == "polygon":
                out.append("close()")
        elif tag == "rect":
            x, y, w, h = (float(attrs[k]) for k in ("x", "y", "width", "height"))
            corners = [(x, y), (x + w, y), (x + w, y + h), (x, y + h)]
            out.append(point(str(corners[0][0]), str(corners[0][1]), "moveTo"))
            out += [point(str(cx), str(cy), "lineTo") for cx, cy in corners[1:]]
            out.append("close()")
        elif tag == "path":
            out += path_commands(attrs["d"], where)
        else:
            sys.exit(f"{where} isn't a shape the icon grid uses")
    if not out:
        sys.exit(f"{svg.name}: no shapes found")
    return out


def property_name(stem: str) -> str:
    first, *rest = stem.split("-")
    return first + "".join(part.title() for part in rest)


def main() -> None:
    blocks = []
    for svg in sorted(ICONS.glob("*.svg")):
        body = "\n".join(f"            {command}" for command in commands_for(svg))
        blocks.append(
            f"    val {property_name(svg.stem)}: ImageVector by lazy {{\n"
            f'        icon("{svg.stem}") {{\n{body}\n        }}\n    }}\n'
        )
    OUT.write_text(HEADER + "\n".join(blocks) + FOOTER, encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)} ({len(blocks)} icons)")


if __name__ == "__main__":
    main()
